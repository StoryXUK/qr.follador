function translateToSpanish(englishHtml) {
    return SPANISH_PHRASES.reduce((text, [pattern, replacement]) => {
        return text.replace(pattern, match => {
            const translated = match.charAt(0) === match.charAt(0).toUpperCase() && match.charAt(0) !== match.charAt(0).toLowerCase()
                ? replacement.charAt(0).toUpperCase() + replacement.slice(1)
                : replacement;
            return translated;
        });
    }, englishHtml);
}

// Spanish copy that is not written out per page is derived from the English page data.
function deriveSpanishPageSet(pageEnglish, pageSpanish) {
    const derived = {};
    Object.keys(pageEnglish).forEach(key => {
        if (pageSpanish[key] !== undefined) return;
        const value = pageEnglish[key];
        if (key === "ingredients_text" || key === "bottled_text") derived[key] = translateToSpanish(value);
        else if (key === "title" || key === "subtitle" || key.endsWith("_value")) derived[key] = key.endsWith("_value") ? value.replace(/(\d)\.(\d)/g, "$1,$2") : value;
    });
    return derived;
}

function getMergedTranslations(pageKey, lang) {
    const globalSet = (translations.global && translations.global[lang]) || {};
    const productPages = ["azzurra", "joani", "torri-di-credazzo", "brut", "extra-dry", "rose", "lugana", "aeris", "doc-dry", "el-brolo", "farder", "aeris-piccolo", "runier", "spago", "valbon"];
    const productSet = productPages.includes(pageKey)
        ? (translations.product && translations.product[lang]) || {}
        : {};
    const explicitSet = (translations[pageKey] && translations[pageKey][lang]) || {};
    const pageSet = lang === "es" && translations[pageKey] && translations[pageKey].en
        ? { ...deriveSpanishPageSet(translations[pageKey].en, explicitSet), ...explicitSet }
        : explicitSet;
    return { ...globalSet, ...productSet, ...pageSet };
}

// Older pages ship "English | Italiano" copy inline; split it so only the selected language shows.
const LEGACY_SLASH_PAIRS = [
    /^Raccolta differenziata\/waste sorting$/i,
    /^Rifiuti Organici\/Organic waste$/i,
    /^Imbottigliato in atmosfera protettiva\/bottled in a protective atmosphere\.?$/i,
    /^di cui Zuccheri\/of which sugars$/i
];

function splitLegacyText(raw) {
    const text = raw.replace(/\s+/g, " ").trim();
    if (!text) return null;
    if (text.includes("|")) {
        const parts = text.split("|").map(part => part.trim());
        return parts.length === 2 && parts[0] && parts[1] ? { en: parts[0], it: parts[1] } : null;
    }
    if (LEGACY_SLASH_PAIRS.some(pattern => pattern.test(text))) {
        const [it, en] = text.split("/").map(part => part.trim());
        return { en: en.charAt(0).toUpperCase() + en.slice(1), it };
    }
    return null;
}

function prepareLegacyPage() {
    if (document.body.hasAttribute("data-page") || document.querySelector("[data-i18n]:not([data-i18n='language_label'])")) return;

    const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT);
    const textNodes = [];
    while (walker.nextNode()) {
        const node = walker.currentNode;
        const parent = node.parentElement;
        if (!parent || parent.closest("script, style, .language-switcher-wrap")) continue;
        textNodes.push(node);
    }
    textNodes.forEach(node => {
        const pair = splitLegacyText(node.nodeValue);
        if (!pair) return;
        const span = document.createElement("span");
        span.setAttribute("data-legacy-en", pair.en);
        span.setAttribute("data-legacy-it", pair.it);
        const spanish = SPANISH_LEGACY_LABELS[pair.en.toLowerCase()];
        if (spanish) span.setAttribute("data-legacy-es", spanish);
        else console.warn("Missing Spanish copy for: " + pair.en);
        node.replaceWith(span);
    });

    // Separate English and Italian paragraphs written one after the other.
    document.querySelectorAll("p").forEach(paragraph => {
        if (paragraph.closest(".language-switcher-wrap") || paragraph.hasAttribute("data-lang-only")) return;
        const text = paragraph.textContent.replace(/\s+/g, " ").trim();
        if (/^(Grapes|Bottled in a protected)/.test(text)) paragraph.setAttribute("data-lang-only", "en");
        else if (/^(uve\b|Imbottigliato in atmosfera protetta\.?$)/i.test(text)) paragraph.setAttribute("data-lang-only", "it");
    });

    // Spanish paragraphs: keep hand-written ones, otherwise derive from the English paragraph.
    document.querySelectorAll("p[data-lang-only='en']").forEach(paragraph => {
        const next = paragraph.nextElementSibling;
        if (next && next.getAttribute("data-lang-only") === "es") return;
        const spanish = paragraph.cloneNode(true);
        spanish.setAttribute("data-lang-only", "es");
        spanish.innerHTML = translateToSpanish(paragraph.innerHTML);
        paragraph.after(spanish);
    });
}

function applyLegacyLanguage(lang) {
    document.querySelectorAll("[data-legacy-en]").forEach(element => {
        element.textContent = element.getAttribute("data-legacy-" + lang) || element.getAttribute("data-legacy-en");
    });
    document.querySelectorAll("[data-lang-only]").forEach(element => {
        element.style.display = element.getAttribute("data-lang-only") === lang ? "" : "none";
    });
}

function setLanguage(lang) {
    const activeTranslations = getMergedTranslations(getPageKey(), lang);
    applyLegacyLanguage(lang);

    document.querySelectorAll("[data-i18n]").forEach(element => {
        const value = activeTranslations[element.getAttribute("data-i18n")];
        if (value !== undefined) element.innerHTML = value;
    });

    const spanishQrSection = document.getElementById("spanishQrSection");
    if (spanishQrSection) spanishQrSection.style.display = lang === "es" ? "block" : "none";

    document.documentElement.lang = lang;

    try {
        localStorage.setItem("selectedLanguage", lang);
    } catch (error) {
        console.warn("Could not save language preference.", error);
    }
}

function detectLanguage(supportedLanguages) {
    const preferred = (navigator.languages && navigator.languages.length
        ? Array.from(navigator.languages)
        : [navigator.language || navigator.userLanguage || "en"]);
    for (const tag of preferred) {
        const code = String(tag).split("-")[0].toLowerCase();
        if (["it", "es"].includes(code) && supportedLanguages.includes(code)) return code;
        if (code === "en") return "en";
    }
    return "en";
}

document.addEventListener("DOMContentLoaded", function () {
    const languageSelect = document.getElementById("languageSelect");
    const langDisplay = document.getElementById("langDisplay");

    if (!languageSelect) return;

    prepareLegacyPage();

    const supportedLanguages = Array.from(languageSelect.options, option => option.value);
    let savedLanguage = "";
    try {
        savedLanguage = localStorage.getItem("selectedLanguage") || "";
    } catch (error) {
        console.warn("Could not read language preference.", error);
    }

    const activeLanguage = supportedLanguages.includes(savedLanguage)
        ? savedLanguage
        : detectLanguage(supportedLanguages);

    function updateLanguage(lang) {
        languageSelect.value = lang;
        setLanguage(lang);
        const selectedOption = languageSelect.querySelector(`option[value="${lang}"]`);
        if (langDisplay && selectedOption) langDisplay.textContent = selectedOption.textContent;
    }

    updateLanguage(activeLanguage);
    languageSelect.addEventListener("change", function () {
        updateLanguage(this.value);
    });
});
