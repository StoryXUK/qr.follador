function getPageKey() {
    return document.body.getAttribute("data-page") || "";
}

function getMergedTranslations(pageKey, lang) {
    const globalSet = (translations.global && translations.global[lang]) || {};
    const productPages = ["azzurra", "joani", "brut", "extra-dry", "rose"];
    const productSet = productPages.includes(pageKey)
        ? (translations.product && translations.product[lang]) || {}
        : {};
    const pageSet = (translations[pageKey] && translations[pageKey][lang]) || {};
    return { ...globalSet, ...productSet, ...pageSet };
}

function setLanguage(lang) {
    const activeTranslations = getMergedTranslations(getPageKey(), lang);

    document.querySelectorAll("[data-i18n]").forEach(element => {
        const value = activeTranslations[element.getAttribute("data-i18n")];
        if (value !== undefined) element.innerHTML = value;
    });

    const spanishQrSection = document.getElementById("spanishQrSection");
    if (spanishQrSection) spanishQrSection.style.display = lang === "es" ? "block" : "none";

    document.documentElement.lang = lang;

    try {
        localStorage.setItem("selectedLanguage", lang);
    } catch (error) {
        console.warn("Could not save language preference.", error);
    }
}

function detectLanguage(supportedLanguages) {
    const deviceLanguage = (navigator.language || navigator.userLanguage || "en")
        .split("-")[0]
        .toLowerCase();
    return supportedLanguages.includes(deviceLanguage) ? deviceLanguage : "en";
}

document.addEventListener("DOMContentLoaded", function () {
    const languageSelect = document.getElementById("languageSelect");
    const langDisplay = document.getElementById("langDisplay");

    if (!languageSelect) return;

    const supportedLanguages = Array.from(languageSelect.options, option => option.value);
    let savedLanguage = "";
    try {
        savedLanguage = localStorage.getItem("selectedLanguage") || "";
    } catch (error) {
        console.warn("Could not read language preference.", error);
    }

    const activeLanguage = supportedLanguages.includes(savedLanguage)
        ? savedLanguage
        : detectLanguage(supportedLanguages);

    function updateLanguage(lang) {
        languageSelect.value = lang;
        setLanguage(lang);
        const selectedOption = languageSelect.querySelector(`option[value="${lang}"]`);
        if (langDisplay && selectedOption) langDisplay.textContent = selectedOption.textContent;
    }

    updateLanguage(activeLanguage);
    languageSelect.addEventListener("change", function () {
        updateLanguage(this.value);
    });
});
